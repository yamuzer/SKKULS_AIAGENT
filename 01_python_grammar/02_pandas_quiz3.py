# ------------------------------------------------------------
# 9. 지역은 오름차순, 3월 매출은 내림차순 정렬
# ------------------------------------------------------------
sorted_frame = frame.sort_values(
    by=["지역", "3월"],
    ascending=[True, False]
)

print("지역 오름차순, 3월 매출 내림차순 정렬")
print(sorted_frame)
print()


# ------------------------------------------------------------
# 10. 원본을 유지하고 지역 열 삭제
# ------------------------------------------------------------
frame_without_region = frame.drop(
    columns="지역"
)

print("지역 열을 삭제한 새로운 DataFrame")
print(frame_without_region)
print()

print("지역 열이 유지된 원본 DataFrame")
print(frame)
print()


# ------------------------------------------------------------
# 11. map을 이용하여 3월 매출 표시 형식 변경
# ------------------------------------------------------------
def format_sales(value):
    if pd.isna(value):
        return "미입력"

    return f"{value:.2f}만원"


march_formatted = frame["3월"].map(format_sales)

print("3월 매출 표시 형식 변경")
print(march_formatted)
print()


# 변환 결과를 새로운 열로 추가
frame["3월_표시"] = march_formatted

print("최종 DataFrame")
print(frame)