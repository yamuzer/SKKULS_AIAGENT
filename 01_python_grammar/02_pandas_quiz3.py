import pandas as pd
import numpy as np


# ------------------------------------------------------------
# 1. DataFrame 생성
# ------------------------------------------------------------
data = {
    "지점명": ["강남점", "홍대점", "해운대점", "송도점", "대전점", "수원점"],
    "지역": ["서울", "서울", "부산", "인천", "대전", "경기"],
    "1월": [82, 75, 90, 68, 77, 85],
    "2월": [88, np.nan, 92, 74, 80, 81],
    "3월": [91, 79, 95, np.nan, 83, 87]
}

index = ["S101", "S102", "S103", "S104", "S105", "S106"]

frame = pd.DataFrame(data, index=index)

frame.index.name = "지점코드"

print("전체 데이터")
print(frame)
print()


# ------------------------------------------------------------
# 2. 데이터의 기본 정보 확인
# ------------------------------------------------------------
print("앞에서부터 5개 행")
print(frame.head())
print()

print("DataFrame 정보")
frame.info()
print()

print("수치형 데이터의 기술 통계")
print(frame.describe())
print()


# ------------------------------------------------------------
# 3. loc를 이용한 데이터 선택
# S102부터 S105까지의 지점명과 월별 매출
# ------------------------------------------------------------
print("S102부터 S105까지의 매출")
print(frame.loc["S102":"S105", ["지점명", "1월", "2월", "3월"]])
print()


# ------------------------------------------------------------
# 4. iloc를 이용한 데이터 선택
# 앞에서부터 3개 지점의 1월과 2월 매출
# ------------------------------------------------------------
print("앞에서부터 3개 지점의 1월과 2월 매출")
print(frame.iloc[:3, 2:4])
print()


# ------------------------------------------------------------
# 5. 3월 매출이 85 이상인 지점 조회
# ------------------------------------------------------------
march_condition = frame["3월"] >= 85

print("3월 매출이 85 이상인 지점")
print(
    frame.loc[
        march_condition,
        ["지점명", "지역", "3월"]
    ]
)
print()


# ------------------------------------------------------------
# 6. 목표 매출 열 추가
# ------------------------------------------------------------
target = pd.Series(
    [85, 80, 90, 75, 82, 84],
    index=["S101", "S102", "S103", "S104", "S105", "S106"]
)

frame["목표매출"] = target

print("목표 매출 추가 결과")
print(frame)
print()


# ------------------------------------------------------------
# 7. 월별 매출 평균 계산
# ------------------------------------------------------------
month_columns = ["1월", "2월", "3월"]

# 결측값을 제외하고 평균 계산
month_mean = frame[month_columns].mean()

print("결측값을 제외한 월별 평균")
print(month_mean)
print()

# 결측값을 포함하여 평균 계산
# 결측값이 있는 열의 결과는 NaN이 된다.
month_mean_with_nan = frame[month_columns].mean(skipna=False)

print("결측값을 포함한 월별 평균")
print(month_mean_with_nan)
print()


# ------------------------------------------------------------
# 8. 지점별 최고 매출과 최저 매출의 차이 계산
# ------------------------------------------------------------
def calculate_sales_difference(row):
    return row.max() - row.min()


frame["매출차이"] = frame[month_columns].apply(
    calculate_sales_difference,
    axis=1
)

print("매출 차이 추가 결과")
print(frame)
print()


