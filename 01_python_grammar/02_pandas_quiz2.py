# 문제1 : 지역별 지점 매출 분석
# 한 회사에서 지역별 지점의 월별 매출을 관리하려고 합니다. 다음 데이터를 이용하여 지점 실적을 분석하는 프로그램을 작성하세요.
import pandas as pd
import numpy as np

data = {
    "지점명": ["강남점", "홍대점", "해운대점", "송도점", "대전점", "수원점"],
    "지역": ["서울", "서울", "부산", "인천", "대전", "경기"],
    "1월": [82, 75, 90, 68, 77, 85],
    "2월": [88, np.nan, 92, 74, 80, 81],
    "3월": [91, 79, 95, np.nan, 83, 87]
}
index = ["S101", "S102", "S103", "S104", "S105", "S106"]
# 요구사항
print("1. `data`와 `index`를 이용하여 DataFrame을 생성하고, 인덱스 이름을 `지점코드`로 지정하세요.")
df = pd.DataFrame(data, index=index)
df.index.name = "지점코드"
print(df)
print()

print("2. `head()`, `info()`, `describe()`를 이용하여 데이터의 기본 정보를 확인하세요.")
print(df.head())
print(df.info())
print(df.describe())
print()

print("3. `loc`를 이용하여 `S102`부터 `S105`까지의 지점명과 1월·2월·3월 매출을 출력하세요.")
print(df.loc["S102":"S105", "1월":])
print()

print("4. `iloc`를 이용하여 앞에서부터 3개 지점의 1월과 2월 매출을 출력하세요.")
print(df.iloc[:3, [2,3]])
print()

print("5. 3월 매출이 85 이상인 지점의 지점명, 지역, 3월 매출을 출력하세요.")
print( df[df["3월"] >= 85])
print( df[df["3월"] >= 85][['지점명','지역', '3월']] )
print()

print("6. 지점별 매출 목표를 담은 다음 Series를 `목표매출` 열로 추가하세요.")
target = pd.Series(
    [85, 80, 90, 75, 82, 84],
    index=["S101", "S102", "S103", "S104", "S105", "S106"]
)
df['목표매출'] = target
print(df)
print()

print("7. 월별 매출 평균을 계산하고, 결측값을 포함하여 계산했을 때의 결과도 비교하세요.")
print(df.loc[:, ["1월","2월","3월"]].mean())
print(df.loc[:, ["1월","2월","3월"]].mean(skipna=False))
print()

print("8. 1월·2월·3월 매출을 기준으로 각 지점의 최고 매출과 최저 매출의 차이를 계산하여 `매출차이` 열로 추가하세요. `apply()`를 사용하세요.")
def sales_diff(x) :
    return x.max() - x.min()
print(df.loc[:,["1월","2월","3월"]])
print(df.loc[:,["1월","2월","3월"]].apply(sales_diff, axis=1))
df['매출차이'] = df.loc[:,["1월","2월","3월"]].apply(sales_diff, axis=1)
print(df)
print()

print("9. 지역은 오름차순, 3월 매출은 내림차순으로 정렬하세요.")
print(df.sort_values(by = ['지역', '3월'], ascending=[True, False]))

print("10. 원본을 유지한 채 `지역` 열을 삭제한 새로운 DataFrame을 만드세요.")
df1 = df.drop(['지역'], axis=1)
print(df1)
print()

print("11. 3월 매출을 `91.00만원`과 같은 형식의 문자열로 변환하세요. `map()`을 사용하고 결측값은 `미입력`으로 표시하세요.")
def f1(x):
    x = str(x) + "만원"
    return x
print(df1['3월'].map(f1, na_action='ignore').fillna('미입력'))

