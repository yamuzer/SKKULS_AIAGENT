# 문제 1. 정규표현식 기반 고객 문의 데이터 정제
#
#
# 입력 파일
# - data/customer_inquiries/quiz.csv
# - 데이터 수: 360건
# - 주요 컬럼: `문의ID`, `고객명`, `국가`, `접수채널`, `문의유형`, `원본문의`
#
# 문제 상황
# 고객 문의 본문에는 날짜, 전화번호, 주문번호, HTML 강조 태그가 섞여 있습니다. 문의 본문을 분석하기 쉬운 구조로 변환해야 합니다.
#
# 구현 요구사항
# 1. data/customer_inquiries.csv를 pandas DataFrame으로 읽으세요.
# 2. 정규표현식은 가능한 한 re.compile()로 미리 준비하세요.
# 3. 원본문의에서 `YYYY-MM-DD` 형식의 날짜를 찾고 다음 컬럼을 만드세요.
#    - `접수일`
#    - `연도`
#    - `월`
#    - `일`
#    - 이름 있는 그룹 `(?P<year>...)`을 사용하세요.
#
# 4. 전화번호를 모두 찾으세요.
#    - 허용 예: `010-1234-5678`, `02-123-4567`, `031-1234-5678`
#    - `전화번호목록`: 여러 번호가 있으면 `, `로 연결
#    - `전화번호수`: 발견한 전화번호 개수
#
# 5. `ORD-2026-00001` 형식의 주문번호를 모두 찾아 다음 컬럼을 만드세요.
#    - `주문번호목록`
#    - `주문번호수`
#
# 6. `<b>...</b>` 안의 문구를 모두 추출하여 `강조문구` 컬럼에 ` | `로 연결하세요.
#    - 한 문의에 `<b>` 태그가 여러 개 있을 수 있으므로 lazy 패턴을 사용하세요.
#
# 7. `정제문의` 컬럼을 만드세요.
#    - 모든 HTML 태그 제거
#    - 전화번호의 마지막 네 자리를 `****`로 마스킹
#    - 연속된 공백·줄바꿈을 하나의 공백으로 정리
#
# 8. 날짜나 전화번호 등이 없는 행에서도 오류가 발생하지 않게 처리하세요.
#
# 9. 정제 결과를 data/customer_inquiries_cleaned.csv로 저장하세요.
#
# 10. 실행 마지막에 다음 내용을 출력하세요.
#     - 전체 문의 수
#     - 전화번호가 발견된 문의 수
#     - 주문번호가 발견된 문의 수
#     - 접수채널별 문의 건수
#     - 문의유형별 문의 건수
#
# 확인 예시
# 원본문의가 다음과 같다고 가정합니다.
#
# ```
# 2026-07-12에 <b>환불 처리</b><b>카드 승인 취소</b>를 요청했습니다. 주문번호 ORD-2026-00125, 연락처 010-1234-5678
# ```
#
# 일부 결과는 다음처럼 나와야 합니다.
#
# ```
# 접수일: 2026-07-12
# 연도: 2026
# 월: 07
# 일: 12
# 전화번호목록: 010-1234-5678
# 주문번호목록: ORD-2026-00125
# 강조문구: 환불 처리 | 카드 승인 취소
# 정제문의: 2026-07-12에 환불 처리카드 승인 취소를 요청했습니다. 주문번호 ORD-2026-00125, 연락처 010-1234-****